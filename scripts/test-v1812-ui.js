'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const root = path.resolve(__dirname, '..');
const dashboard = fs.readFileSync(path.join(root, 'src/ts/study/dashboard.ts'), 'utf8');
const game = fs.readFileSync(path.join(root, 'src/ts/core/game.ts'), 'utf8');
const css = fs.readFileSync(path.join(root, 'src/css/study.css'), 'utf8');
assert(dashboard.includes("node('p', list, 'No studies yet. Create your first study above.').className = 'study-empty-studies';"));
assert(/\.study-admin-dashboard \.study-empty-studies\s*\{\s*padding-bottom:\s*18px;\s*\}/.test(css), 'Empty study state must have bottom space');
assert(dashboard.includes('Upload JSON levels here once, then assign them when creating or modifying studies.'));
assert(dashboard.includes('Participant login password. Share it securely.'));
assert(game.includes("button.className = 'study-login-submit'"));
assert(css.includes('.study-login-card h1 {\n  color:#33ff66!important;\n  text-shadow:none!important;'), 'Login heading must be green without a glow');
assert(css.includes('button.study-login-submit:hover:not(:disabled)') && css.includes('background:#209b46!important;'), 'Login should turn brighter green on hover');
assert(css.includes('box-shadow:none!important;\n  text-shadow:none!important;'), 'Login button must not glow');
assert(dashboard.includes('uploadedDate ? `${level.name} (${uploadedDate})` : level.name'));
const helper = dashboard.match(/function levelDate\(iso\?: string\): string \{[\s\S]*?\n\}/);
assert(helper, 'Upload-date formatter missing');
const js = helper[0].replace('iso?: string): string', 'iso)') + '\nlevelDate;';
const format = vm.runInNewContext(js, { Date, Number, displayDate: iso => {
  const parts = /^\d{4}-\d{2}-\d{2}/.exec(iso);
  return parts ? `${iso.slice(8, 10)}-${iso.slice(5, 7)}-${iso.slice(0, 4)}` : iso;
} });
assert.equal(format('2026-11-05T23:12:01.000Z'), '05-11-2026');
assert.equal(format('not-a-date'), '');
assert.equal(format(undefined), '');
console.log('PASS: empty study spacing, green no-glow login, updated levels copy, upload-date handling and participant tooltip');
