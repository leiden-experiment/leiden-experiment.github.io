'use strict';
/** Schedule tests for both calendar modes. No Firebase credentials required. */
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const ts = (() => { try { return require('typescript'); }
  catch { return require('/opt/nvm/versions/node/v22.16.0/lib/node_modules/typescript'); } })();
const root = path.resolve(__dirname, '..');
const compiled = ts.transpileModule(fs.readFileSync(path.join(root, 'src/ts/study/types.ts'), 'utf8'),
  {compilerOptions: {target: ts.ScriptTarget.ES2020, module: ts.ModuleKind.CommonJS}}).outputText;
const studyExports = {};
vm.runInNewContext(compiled, {exports: studyExports, Date, Object, Array, Math, Number, String, JSON});
const {defaultStudySettings, emptyProgress, getNextAssignment, validateSettings} = studyExports;
const level = {type:'level',levelId:'legacy:Trained',bpmIndex:0,loops:1};
const weeks = {'0':[level], '1':[level], '2':[level], '3':[level], '-1':[level]};
const base = {...defaultStudySettings(), weeklyEnabled:true, maxSessionsPerWeek:2, weeks};
const fixed = {...base, scheduleMode:'fixed', startDate:'2026-11-15', endDate:'2026-12-05', durationWeeks:undefined};
const before = getNextAssignment(fixed, emptyProgress(), '', new Date('2026-11-08T14:00:00Z'));
assert.equal(before.week, 0, 'Pre-test is permitted before the fixed research calendar');
assert.equal(before.capped, false);
const afterPretest = {...emptyProgress(), sessions:{'0':1}};
const waiting = getNextAssignment(fixed, afterPretest, '', new Date('2026-11-08T14:00:00Z'));
assert.equal(waiting.week,1); assert.equal(waiting.beforeStart,true); assert.equal(waiting.capped,true);
const start = getNextAssignment(fixed, afterPretest, '2099-01-01', new Date('2026-11-15T12:00:00Z'));
assert.equal(start.week,1); assert.equal(start.capped,false, 'A participant start date cannot override a fixed calendar');
const mid = getNextAssignment(fixed, afterPretest, '', new Date('2026-11-23T12:00:00Z'));
assert.equal(mid.week,2); assert.equal(mid.capped,false);
const limit = getNextAssignment(fixed, {...afterPretest,sessions:{'0':1,'2':2}}, '', new Date('2026-11-23T12:00:00Z'));
assert.equal(limit.state,'weekly-complete'); assert.equal(limit.daysUntilNextWeek,6);
const end = getNextAssignment(fixed, afterPretest, '', new Date('2026-12-06T12:00:00Z'));
assert.equal(end.state,'awaiting-posttest'); assert.equal(end.capped,true);
const released = getNextAssignment(fixed, {...afterPretest,stageOverride:{week:-1,sessionNumber:4}}, '', new Date('2026-12-06T12:00:00Z'));
assert.equal(released.week,-1); assert.equal(released.capped,false);
const complete = getNextAssignment(fixed, {...afterPretest,sessions:{'0':1,'-1':1}}, '', new Date('2026-12-07T12:00:00Z'));
assert.equal(complete.state,'completed'); assert.equal(complete.capped,true);
assert.equal(getNextAssignment(fixed,{...afterPretest,sessions:{'0':1,'-1':1},stageOverride:{week:1,sessionNumber:99}},'',new Date('2026-12-07')).capped,false,'Researcher stage override must allow replay after Post-test completion');
assert.equal(validateSettings(fixed).length,0);
assert(validateSettings({...fixed,endDate:''}).some(s=>s.includes('week count')));
assert.equal(validateSettings({...fixed,endDate:'',durationWeeks:3}).length,0,'Fixed studies can use a duration without an explicit end date');
assert(validateSettings({...fixed,endDate:'2026-11-14'}).some(s=>s.includes('precede')));
const individual = {...base, scheduleMode:'individual',durationWeeks:2,participantStartMode:'first-login',endDate:'',dateRangeEnabled:false};
assert.equal(validateSettings(individual).length,0);
const noStart = getNextAssignment(individual, afterPretest, '', new Date('2026-11-20T12:00:00Z'));
assert.equal(noStart.capped,true); assert.equal(noStart.state,'waiting-start');
const personWeek1 = getNextAssignment(individual, afterPretest, '2026-11-20', new Date('2026-11-26T12:00:00Z'));
assert.equal(personWeek1.week,1); assert.equal(personWeek1.capped,false);
const personWeek2 = getNextAssignment(individual, afterPretest, '2026-11-20', new Date('2026-11-27T12:00:00Z'));
assert.equal(personWeek2.week,2);
const shifted = getNextAssignment(individual, afterPretest, '2026-11-27', new Date('2026-11-27T12:00:00Z'));
assert.equal(shifted.week,1,'Researcher-adjusted dates must move the participant back to the new first week');
const endIndividual = getNextAssignment(individual, afterPretest, '2026-11-20', new Date('2026-12-04T12:00:00Z'));
assert.equal(endIndividual.state,'awaiting-posttest');
const waitingRelogin = getNextAssignment(individual, {...afterPretest,pretestPendingLogin:true}, '2026-11-20', new Date('2026-11-21T12:00:00Z'));
assert.equal(waitingRelogin.state,'awaiting-login'); assert.equal(waitingRelogin.capped,true);
const single={...base, weeklyEnabled:false, weeks:{'1':[level]}};
assert.equal(getNextAssignment(single, emptyProgress(), '2010-01-01', new Date('2026-11-20T12:00:00Z')).week,1);
const scene=fs.readFileSync(path.join(root,'src/ts/scenes/studySessionScene.ts'),'utf8');
assert(scene.includes("if (step?.type === 'end'"));
const endSection=scene.slice(scene.indexOf("if (step?.type === 'end'"),scene.indexOf('if (plan && !plan.capped'));
assert(!endSection.includes('new Button(') && !endSection.includes('addStudyUtilityButtons'),
 'End slide must never have camera, Settings, Retry or Continue buttons');
assert(scene.includes('daysUntilNextWeek'));
const dashboard=fs.readFileSync(path.join(root,'src/ts/study/dashboard.ts'),'utf8');
assert(dashboard.includes('Fixed schedule — all participants') && dashboard.includes('Individual schedule — starts'));
assert(dashboard.includes('setStudyEnabled(study.id') && dashboard.includes('Study start date (Week 1)'));
console.log('PASS: fixed/individual weekly calendars, Pre-test access, next-week countdown, manual Post-test, researcher replays after completion, single-session compatibility, End slide and study enabled controls');
